#[test]
fn seeded_order_is_permutation_and_preserves_active_pairs() -> Check {
    let mut seed = 9483392_u64;
    let mut next = |n| {
        seed = seed.wrapping_mul(6364136223846793005).wrapping_add(1);
        ((seed >> 32) as i64) % n
    };
    for case in 0..400 {
        let items: Vec<_> = (0..1 + next(29))
            .map(|_| {
                let start = next(80) * 10;
                cue(start, start + 10 + next(24) * 10)
            })
            .collect();
        let order = document::presentation_order(&items, "ass")?;
        assert_eq!(
            order.iter().copied().collect::<BTreeSet<_>>(),
            (0..items.len()).collect(),
            "case {case}"
        );
        let mut rank = vec![0; items.len()];
        for (position, &original) in order.iter().enumerate() {
            rank[original] = position;
        }
        for (i, first) in items.iter().enumerate() {
            for (j, second) in items.iter().enumerate().skip(i + 1) {
                if first.start.max(second.start) < first.end.min(second.end) {
                    assert!(rank[i] < rank[j], "case {case}");
                }
            }
        }
        let sorted: Vec<_> = order.iter().map(|&i| items[i].clone()).collect();
        assert_eq!(
            document::presentation_order(&sorted, "ass")?,
            (0..items.len()).collect::<Vec<_>>()
        );
    }
    Ok(())
}

