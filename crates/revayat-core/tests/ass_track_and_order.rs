fn selected(
    items: &[(i64, i64)],
    all: bool,
    changes: &[i64],
) -> Result<(Document, Vec<Value>, BTreeSet<i64>), String> {
    let doc = Document {
        kind: "ass".into(),
        cues: items.iter().map(|&(a, b)| cue(a, b)).collect(),
        ..Default::default()
    };
    let plan = samples(&doc, all, changes)?;
    let indices = plan
        .iter()
        .flat_map(|s| s["cue_indices"].as_array().into_iter().flatten())
        .filter_map(Value::as_i64)
        .collect();
    Ok((doc, plan, indices))
}

#[test]
fn sample_times_cover_temporal_edges_in_nonchronological_rows() -> Check {
    let (doc, plan, indices) = selected(
        &[(3000, 10000), (0, 10000), (9000, 10000), (2000, 10000)],
        false,
        &[],
    )?;
    assert!(BTreeSet::from([2, 3]).is_subset(&indices));
    for sample in plan {
        let time = sample["time_seconds"].as_f64().ok_or("sample time")?;
        for index in sample["cue_indices"].as_array().ok_or("indices")? {
            let cue = &doc.cues[index.as_u64().ok_or("index")? as usize - 1];
            assert!((cue.start as f64 / 1000.0..cue.end as f64 / 1000.0).contains(&time));
        }
    }
    Ok(())
}

