fn style(name: &str) -> String {
    format!(
        "Style: {name},Arial,42,&H00FFFFFF,&H000000FF,&H00000000,&H80000000,0,0,0,0,100,100,0,0,1,2,1,2,30,30,35,1"
    )
}

fn track(styles: &[&str], headers: &str, rows: &str) -> String {
    let styles = styles
        .iter()
        .map(|name| style(name))
        .collect::<Vec<_>>()
        .join("\n");
    format!(
        "[Script Info]\nScriptType: v4.00+\nPlayResX: 320\nPlayResY: 180\n{headers}\n[V4+ Styles]\nFormat: {STYLE_FIELDS}\n{styles}\n[Events]\nFormat: {ASS_FIELDS}\n{rows}\n"
    )
}

fn event(label: &str, name: &str, text: &str) -> String {
    format!("{label}: 0,0:00:01.00,0:00:03.00,{name},,0,0,0,,{text}")
}

fn source() -> String {
    track(&["Default"], "", &event("Dialogue", "Default", "VISIBLE"))
}
fn ass(text: &str) -> Result<Document, String> {
    document::parse(text, "ass")
}
fn saved(doc: &Document) -> Result<String, String> {
    document::serialize(doc, &doc.cues, false)
}
fn error<T: std::fmt::Debug>(result: Result<T, String>, message: &str) {
    let actual = result.expect_err(message);
    assert!(
        actual.contains(message),
        "{actual:?} must contain {message:?}"
    );
}

macro_rules! refuses {
    ($($name:ident: ($input:expr, $message:literal)),+ $(,)?) => {$ (
        #[test]
        fn $name() { error(ass(&$input), $message); }
    )+};
}

