_ASS_CASE = str.maketrans("ABCDEFGHIJKLMNOPQRSTUVWXYZ", "abcdefghijklmnopqrstuvwxyz")
ASS_NATIVE_SECTIONS = frozenset({"[script info]", "[v4+ styles]", "[v4 styles]", "[events]", "[fonts]"})
ASS_RENDER_HEADERS = ("ScriptType", "PlayResX", "PlayResY", "LayoutResX", "LayoutResY",
                      "Timer", "WrapStyle", "ScaledBorderAndShadow", "Kerning", "YCbCr Matrix", "Language")


def ass_key(value: str) -> str:
    """Fold ASCII grammar names without changing Unicode identifiers or prose."""
    return value.translate(_ASS_CASE)


def ass_line_start(value: str) -> str:
    """Match the reader's BOM-then-ASCII-indent handling, not Unicode whitespace."""
    return value.lstrip("\ufeff").lstrip(" \t")


def ass_style_name(value: str, *, reference: bool = False) -> str:
    """Resolve declaration/event names; override resets use separate exact names."""
    name = value.lstrip(" \t").lstrip("*")
    if reference:
        return "Default" if ass_key(name) == "default" else name
    return name or "Default"


def _preserve_legacy_scaling(doc) -> None:
    """Materialize the renderer effect of legacy FFmpeg's non-display signature."""
    order = {ass_key(name): index for index, (name, _) in enumerate(doc.sections)}
    info_index, event_index = order.get("[script info]"), order.get("[events]")
    if (info_index is None or event_index is None or info_index > event_index
            or len(doc.styles) != 1 or not next(iter(doc.styles)).startswith("Default")):
        return
    lines = doc.sections[info_index][1]
    flags = set()
    for line in lines:
        raw = ass_line_start(line)
        for header in ASS_RENDER_HEADERS:
            if raw.startswith(header + ":"):
                flags.add(header)
        if raw.startswith("; Script generated by FFmpeg/Lavc"):
            flags.add("generator")
    if flags == {"ScriptType", "PlayResX", "PlayResY", "generator"}:
        # A copied donor or style pruning must not toggle the legacy heuristic.
        lines.append("ScaledBorderAndShadow: yes")


@dataclass
class Cue:
    id: str
    start: int
    end: int
    text: str
    fields: dict[str, str] = field(default_factory=dict)


@dataclass
class Document:
    kind: str
    cues: list[Cue]
    sections: list[tuple[str, list[str]]] = field(default_factory=list)
    event_fields: list[str] = field(default_factory=list)
    style_fields: list[str] = field(default_factory=list)
    styles: dict[str, list[str]] = field(default_factory=dict)
    comments: int = 0
    source_comments: dict[str, list[str]] = field(default_factory=dict)
    chronological: bool = False


def timestamp(value: str, kind: str) -> int:
    if not isinstance(value, str) or kind not in {"ass", "srt"}:
        raise ValueError("Invalid subtitle timestamp or format")
    pattern = (r"([0-9]{1,12}):([0-9]{2}):([0-9]{2})\.([0-9]{2})" if kind == "ass"
               else r"([0-9]{1,12}):([0-9]{2}):([0-9]{2}),([0-9]{3})")
    match = re.fullmatch(pattern, value.strip(" \t"))
    if not match:
        raise ValueError("Invalid subtitle timestamp")
    hours, minutes, seconds, fraction = map(int, match.groups())
    if minutes > 59 or seconds > 59:
        raise ValueError("Subtitle minutes and seconds must be below 60")
    result = ((hours * 60 + minutes) * 60 + seconds) * 1000 + fraction * (10 if kind == "ass" else 1)
    if result > MAX_TIME_MS:
        raise ValueError("Subtitle timestamp exceeds the supported millisecond limit")
    return result


def timecode(ms: int, kind: str) -> str:
    if type(ms) is not int or not 0 <= ms <= MAX_TIME_MS or kind not in {"ass", "srt"}:
        raise ValueError("Timestamp serialization requires nonnegative integer milliseconds and ASS/SRT")
    hours, ms = divmod(ms, 3600000)
    minutes, ms = divmod(ms, 60000)
    seconds, fraction = divmod(ms, 1000)
    if kind == "ass":
        return f"{hours}:{minutes:02}:{seconds:02}.{fraction // 10:02}"
    return f"{hours:02}:{minutes:02}:{seconds:02},{fraction:03}"


def effective_times(start: int, end: int, kind: str) -> tuple[int, int]:
    if type(start) is not int or type(end) is not int or not 0 <= start < end <= MAX_TIME_MS:
        raise ValueError("Cue timing requires nonnegative integers and end after start")
    result = (start // 10 * 10, end // 10 * 10) if kind == "ass" else (start, end)
    if result[1] <= result[0]:
        raise ValueError("Centisecond quantization collapses this cue; review its timing explicitly")
    return result


def parse(data: str, kind: str) -> Document:
    if not isinstance(data, str) or len(data) > 16 * 1024 * 1024:
        raise ValueError("Subtitle text exceeds the supported parse budget")
    data = data.lstrip("\ufeff").replace("\r\n", "\n").replace("\r", "\n")
    if "\x00" in data or "\ufffd" in data:
        raise ValueError("NUL or replacement characters in subtitles; check the input encoding")
    doc = Document(kind, [])
    if kind == "srt":
        def blocks():
            source, cursor = data.strip(), 0
            for match in re.finditer(r"\n[ \t]*\n", source):
                yield source[cursor:match.start()]
                cursor = match.end()
            yield source[cursor:]
        for block in blocks():
            if not block.strip():
                continue
            lines = block.split("\n")
            if len(lines) < 2 or not lines[0].strip().isdigit():
                raise ValueError("Malformed SRT cue; expected a number and timestamp line")
            times = lines[1].split(" --> ")
            if len(times) != 2:
                raise ValueError("Malformed SRT timestamp line")
            start, end = (timestamp(t, kind) for t in times)
            if len(doc.cues) >= 100000:
                raise ValueError("Subtitle exceeds 100000 cues")
            doc.cues.append(Cue(f"c{len(doc.cues) + 1:06}", start, end, "\n".join(lines[2:])))
    elif kind == "ass":
        section, lines = "", []
        seen_sections = set()
        known_sections = {"[script info]", "[v4+ styles]", "[v4 styles]", "[events]", "[fonts]",
                          "[graphics]", "[aegisub project garbage]", "[aegisub extradata]"}
        for line in data.split("\n"):
            stripped = ass_line_start(line).rstrip(" \t")
            folded = ass_key(stripped)
            if any(folded.startswith(name) for name in ASS_NATIVE_SECTIONS) and folded not in ASS_NATIVE_SECTIONS:
                raise ValueError("ASS section header has a renderer-active suffix; repair its spelling explicitly")
            header = stripped.startswith("[") and stripped.endswith("]")
            if ass_key(section) in {"[fonts]", "[graphics]"}:
                header = header and ass_key(stripped) in known_sections
            if header:
                section = stripped
                if ass_key(section) in seen_sections:
                    raise ValueError("Repeated ASS sections are not supported")
                seen_sections.add(ass_key(section))
                lines = []
                doc.sections.append((section, lines))
            elif section:
                lines.append(line)
            elif stripped and not stripped.startswith(";"):
                raise ValueError("ASS content before the first section")
        for section, lines in doc.sections:
            key = ass_key(section)
            if key not in {"[events]", "[v4+ styles]"}:
                if key == "[v4 styles]":
                    raise ValueError("Legacy SSA requires explicit conversion to ASS first")
                if key not in {"[script info]", "[fonts]"}:
                    prefixes = ("Format:", "Style:", "Dialogue:", "; Script generated by FFmpeg/Lavc",
                                *(header + ":" for header in ASS_RENDER_HEADERS))
                    if any(ass_line_start(line).startswith(prefixes) for line in lines):
                        raise ValueError("Renderer-active ASS row outside its supported section; repair a separate source copy")
                continue
            fields = []
            for line in lines:
                if not line.strip() or line.lstrip().startswith(";"):
                    continue
                label, separator, value = ass_line_start(line).partition(":")
                canonical = {"format": "Format", "style": "Style", "dialogue": "Dialogue", "comment": "Comment"}
                raw_label = label.lstrip(" \t")
                label = ass_key(raw_label)
                if label.strip(" \t") in canonical and raw_label != canonical[label.strip(" \t")]:
                    raise ValueError("ASS row labels require canonical spelling and no space before the colon")
                if not separator:
                    raise ValueError("Malformed ASS section row")
                if label == "format":
                    if fields:
                        raise ValueError("Multiple Format rows in an ASS section")
                    fields = [ass_key(s.strip(" \t")) for s in value.split(",")]
                    if len(fields) != len(set(fields)):
                        raise ValueError("Duplicate ASS Format fields")
                    if key == "[events]":
                        if not {"start", "end", "text", "style"} <= set(fields) or fields[-1] != "text":
                            raise ValueError("ASS Events requires Start, End, Style and final Text")
                        doc.event_fields = fields
                    else:
                        if "name" not in fields:
                            raise ValueError("ASS Styles requires a Name field")
                        doc.style_fields = fields
                elif label == "comment" and key == "[events]":
                    doc.comments += 1
                elif label == ("dialogue" if key == "[events]" else "style"):
                    if not value.strip(" \t") and label == "style":
                        raise ValueError("Empty ASS Style rows have renderer defaults; repair them explicitly")
                    if not fields:
                        raise ValueError("ASS rows require a preceding Format")
                    parts = value.lstrip(" \t").split(",", len(fields) - 1)
                    if len(parts) != len(fields):
                        raise ValueError("ASS row does not match its Format")
                    row = dict(zip(fields, parts))
                    if label == "style":
                        name = ass_style_name(row["name"])
                        if name in doc.styles:
                            raise ValueError("Duplicate ASS style name after renderer normalization")
                        doc.styles[name] = parts
                    else:
                        if len(doc.cues) >= 100000:
                            raise ValueError("Subtitle exceeds 100000 cues")
                        doc.cues.append(Cue(f"c{len(doc.cues) + 1:06}", timestamp(row["start"], kind),
                                            timestamp(row["end"], kind), row["text"], row))
                else:
                    raise ValueError("Unsupported ASS row in Events or Styles; inspect before conversion")
        if not doc.event_fields or not doc.style_fields:
            raise ValueError("Missing ASS Events or V4+ Styles Format")
        order = [ass_key(name) for name, _ in doc.sections]
        if order.index("[v4+ styles]") > order.index("[events]"):
            raise ValueError("ASS styles must precede events so style references resolve before rendering")
        _preserve_legacy_scaling(doc)
    else:
        raise ValueError("Supported formats are .ass and .srt")
    if not doc.cues:
        raise ValueError("No subtitle cues found")
    for cue in doc.cues:
        if cue.end <= cue.start:
            raise ValueError(f"Cue {cue.id} ends before or at its start")
    return doc


def visible(text: str, kind: str) -> str:
    result = "".join(value for type_, value in pieces(text, kind) if type_ == "text")
    if kind == "ass":
        result = result.replace(r"\N", "\n").replace(r"\n", " ").replace(r"\h", " ")
        result = result.replace(r"\{", "{").replace(r"\}", "}")
    return result.translate(str.maketrans("", "", BIDI)).strip()


def structure(text: str, kind: str) -> list[tuple[str, str]]:
    return [(type_, value) for type_, value in pieces(text, kind) if type_ != "text"]


def has_drawing(text: str, kind: str) -> bool:
    return any(type_ == "drawing" and value.strip() for type_, value in pieces(text, kind))


def style_references(cue: Cue) -> set[str]:
    refs = {ass_style_name(cue.fields.get("style", "Default"), reference=True)}
    for type_, value in pieces(cue.text, "ass"):
        if type_ == "tag":
            refs.update(argument for name, argument, _, _ in overrides(value)
                        if name == "r" and argument)
    return refs


def presentation_order(cues: list[Cue], kind: str) -> list[int]:
    """Order disjoint time components without changing ASS overlap read order.

    A chronological sort changes the compositing order of active same-layer
    events. Within each connected half-open overlap component retain the input
    order; only components that cannot be active together may be moved. Use the
    emitted timestamps, including ASS centisecond quantization. SRT remains
    chronological. Return indices so cue provenance follows the identical order.
    """
    if kind not in {"ass", "srt"}:
        raise ValueError("Cue ordering requires ASS or SRT format")
    times = [effective_times(cue.start, cue.end, kind) for cue in cues]
    chronological = sorted(range(len(cues)), key=lambda index: times[index][0])
    if kind != "ass":
        return chronological
    ordered, component = [], []
    right = 0
    for index in chronological:
        start, end = times[index]
        if component and start >= right:
            ordered.extend(sorted(component))
            component.clear()
        if not component:
            right = end
        else:
            right = max(right, end)
        component.append(index)
    ordered.extend(sorted(component))
    return ordered


def serialize(doc: Document, cues: list[Cue], remove_fonts: bool = False) -> str:
    if not cues:
        raise ValueError("Refusing an episode with no retained cues")
    if doc.chronological:
        cues = sorted(cues, key=lambda cue: effective_times(cue.start, cue.end, doc.kind)[0])
    else:
        cues = [cues[index] for index in presentation_order(cues, doc.kind)]
    if doc.kind == "srt":
        return "\n\n".join(f"{i}\n{timecode(c.start, 'srt')} --> {timecode(c.end, 'srt')}\n{c.text}"
                           for i, c in enumerate(cues, 1)) + "\n"
    used = set().union(*(style_references(c) for c in cues))
    if used - doc.styles.keys():
        raise ValueError("Subtitle references an undefined ASS style")
    output = []
    for name, lines in doc.sections:
        key = ass_key(name)
        if key == "[aegisub project garbage]" or (remove_fonts and key == "[fonts]"):
            continue
        output.append(name)
        if key == "[events]":
            output.append("Format: " + ", ".join(doc.event_fields))
            for cue in cues:
                row = {**cue.fields, "start": timecode(cue.start, "ass"), "end": timecode(cue.end, "ass"),
                       "text": cue.text}
                if "\n" in cue.text or "\r" in cue.text:
                    raise ValueError("ASS cue text must use literal \\N instead of a physical newline")
                for reference in doc.source_comments.get(cue.id, ()):
                    output.append("Comment: " + ",".join(reference if field_ == "text" else row.get(field_, "")
                                                           for field_ in doc.event_fields))
                output.append("Dialogue: " + ",".join(row.get(field_, "") for field_ in doc.event_fields))
        elif key == "[v4+ styles]":
            output.append("Format: " + ", ".join(doc.style_fields))
            output.extend("Style: " + ",".join(values) for style, values in doc.styles.items() if style in used)
        else:
            output.extend(line for line in lines if line.strip() and
                          (key in {"[fonts]", "[graphics]"} or not line.lstrip().startswith(";")))
        output.append("")
    return "\n".join(output)


def validate_srt_donor_markup(text: str) -> None:
    """Refuse unimplemented decoder markup rather than expose it as ASS prose."""
    for match in re.finditer(r"<([^<>]{0,128})>", text):
        if not srt_tag_fits(match[0]):
            continue
        body = match[1]
        closing = body.startswith("/")
        body = body[1:] if closing else body
        name = body.lstrip(" ").split(" ", 1)[0]
        recognized = (name.lower() in {"b", "i", "s", "u", "font", "br", "br/"}
                      or (not closing and re.match(r"font\s+\S", body, re.I | re.ASCII) is not None))
        likely = (re.fullmatch(r"[A-Za-z0-9_/]*", name) is not None
                  and not body.startswith(" ")
                  and (closing or match.start() == 0 or text[match.start() - 1] != "<"))
        supported = (SRT_BREAK.fullmatch(match[0]) is not None
                     or SRT_COLOR.fullmatch(match[0]) is not None
                     or re.fullmatch(r"</?[bisu]>|</font>", match[0], re.I | re.ASCII) is not None)
        if (recognized or likely) and not supported:
            raise ValueError("SRT donor uses unsupported decoder markup; adapt it explicitly before ASS conversion")


def srt_to_ass(cue: Cue) -> Cue:
    text = uncomment(cue.text.replace("\r\n", "\n").replace("\r", "\n"), "srt")
    validate_srt_donor_markup(text)
    if any(char in SRT_ALIGNMENT.sub("", text) for char in ("{", "}", "\\")):
        raise ValueError("SRT donor contains ASS control syntax; adapt it explicitly before ASS conversion")
    text = convert_srt_markup_to_ass(text)
    if any(type_ == "tag" and not SRT_ALIGNMENT.fullmatch(value) for type_, value in pieces(text, "srt")):
        raise ValueError("SRT donor uses markup requiring explicit ASS adaptation")
    fields = dict(zip([f.strip().lower() for f in ASS_FIELDS.split(",")],
                      ["0", "", "", "Default", "", "0", "0", "0", "", ""]))
    start, end = effective_times(cue.start, cue.end, "ass")
    return Cue(cue.id, start, end, text, fields)


def ass_template(style_line: str | None = None, title: str = "", play_res_x: int = DEFAULT_PLAY_RES_X,
                 play_res_y: int = DEFAULT_PLAY_RES_Y) -> Document:
    style_fields = [ass_key(value.strip()) for value in STYLE_FIELDS.split(",")]
    event_fields = [ass_key(value.strip()) for value in ASS_FIELDS.split(",")]
    style = (DEFAULT_STYLE if style_line is None else style_line.removeprefix("Style:").lstrip()).split(",")
    if len(style) != len(style_fields) or not style[0].strip() or any(c in "".join(style) for c in "\r\n\0"):
        raise ValueError("ASS style must be a single V4+ Style row")
    if any(type(res) is not int or res <= 0 for res in (play_res_x, play_res_y)):
        raise ValueError("ASS script resolution requires positive integers")
    info = ["ScriptType: v4.00+", f"PlayResX: {play_res_x}", f"PlayResY: {play_res_y}",
            "ScaledBorderAndShadow: yes", "WrapStyle: 0"]
    if title:
        if any(c in title for c in "\r\n\0"):
            raise ValueError("ASS title must fit on one line")
        info.insert(0, f"Title: {title}")
    return Document("ass", [], [("[Script Info]", info), ("[V4+ Styles]", []), ("[Events]", [])],
                    event_fields, style_fields, {ass_style_name(style[0]): style})


def srt_document_to_ass(doc: Document, *, style_line: str | None = None, title: str = "",
                        play_res_x: int = DEFAULT_PLAY_RES_X, play_res_y: int = DEFAULT_PLAY_RES_Y,
                        direction: str = "rtl", fix_zwnj: bool = True, strip_watermarks: bool = True,
                        wrap_lines: bool = True, max_chars: int = 42) -> tuple[Document, list[dict]]:
    if doc.kind != "srt":
        raise ValueError("SRT document conversion requires SRT input")
    template = ass_template(style_line, title, play_res_x, play_res_y)
    return _process_ass_document(doc, template, next(iter(template.styles)), direction, fix_zwnj,
                                 strip_watermarks, wrap_lines, max_chars)


def _process_ass_document(doc: Document, result: Document, style: str, direction: str, fix_zwnj: bool,
                          strip_watermarks: bool, wrap_lines: bool, max_chars: int) -> tuple[Document, list[dict]]:
    if direction not in {"rtl", "ltr"}:
        raise ValueError("Paragraph direction must be ltr or rtl")
    if max_chars < 1:
        raise ValueError("Line wrapping requires positive max_chars and max_lines")
    removed = []
    for source in doc.cues:
        effective_times(source.start, source.end, "ass")
        if strip_watermarks and not has_drawing(source.text, doc.kind) and (reason := watermark_reason(source.text)):
            removed.append({"id": source.id, "start_ms": source.start, "end_ms": source.end, "reason": reason,
                            "text": source.text})
            continue
        if doc.kind == "srt":
            cue = srt_to_ass(source)
            cue.fields["style"] = style
        else:
            cue = replace(source, fields=dict(source.fields))
        cue.text = process_ass_text(cue.text, direction, max_chars, fix_zwnj, wrap_lines)
        result.cues.append(cue)
    return result, removed


def ass_document_to_ass(doc: Document, *, style_line: str | None = None, title: str = "", direction: str = "rtl",
                        fix_zwnj: bool = True, strip_watermarks: bool = True, wrap_lines: bool = True,
                        max_chars: int = 42) -> tuple[Document, list[dict]]:
    if doc.kind != "ass":
        raise ValueError("ASS document conversion requires ASS input")
    template = ass_template(style_line, title)
    style, values = next(iter(template.styles.items()))
    by_field = dict(zip(template.style_fields, values))
    # Keep named sign styles and the original coordinate system and effects.
    styles = {**doc.styles, style: [by_field.get(key, "") for key in doc.style_fields]}
    sections = []
    for name, lines in doc.sections:
        if title and ass_key(name) == "[script info]":
            lines = [f"Title: {title}", *(line for line in lines if not ass_key(ass_line_start(line)).startswith("title:"))]
        sections.append((name, list(lines)))
    result = replace(doc, cues=[], sections=sections, styles=styles, comments=0, source_comments={})
    return _process_ass_document(doc, result, style, direction, fix_zwnj, strip_watermarks, wrap_lines, max_chars)


def _source_reference(label: str, text: str) -> str:
    return re.sub(r"\r\n|\r|\n", lambda _: r"\N", f"{label}: {text}").replace("\x00", "")


def build_translator_ass(primary_doc: Document, donor_docs: list[tuple[str, Document]] | None = None, *,
                         include_source_comments: bool = False, style_line: str | None = None, title: str = "",
                         strip_watermarks: bool = True, direction: str = "rtl", fix_zwnj: bool = True,
                         wrap_lines: bool = True, max_chars: int = 42) -> tuple[Document, dict]:
    convert = srt_document_to_ass if primary_doc.kind == "srt" else ass_document_to_ass
    edition, removed = convert(primary_doc, style_line=style_line, title=title, strip_watermarks=strip_watermarks,
                               direction=direction, fix_zwnj=fix_zwnj, wrap_lines=wrap_lines, max_chars=max_chars)
    style = ass_style_name((DEFAULT_STYLE if style_line is None else style_line.removeprefix("Style:")).split(",", 1)[0])
    primary = sorted(edition.cues, key=lambda cue: cue.start)
    starts = [cue.start for cue in primary]
    far_ends = list(accumulate((cue.end for cue in primary), max))
    placeholders: dict[tuple[int, int], Cue] = {}
    source_text = {cue.id: cue.text for cue in primary_doc.cues}
    if include_source_comments:
        edition.source_comments = {cue.id: [_source_reference("Primary", source_text[cue.id])] for cue in primary}
    ids = {cue.id for cue in primary}
    watermark_count = len(removed)
    for label, doc in donor_docs or []:
        for source in doc.cues:
            start, end = effective_times(source.start, source.end, "ass")
            if strip_watermarks and not has_drawing(source.text, doc.kind) and watermark_reason(source.text):
                watermark_count += 1
                continue
            begin, finish = bisect_left(far_ends, start - 150), bisect_right(starts, end + 150)
            best = None
            best_score = -151
            for index in range(begin, finish):
                candidate = primary[index]
                overlap = min(end, candidate.end) - max(start, candidate.start)
                if overlap > best_score and (overlap * 4 > end - start or -150 <= overlap <= 0):
                    best, best_score = candidate, overlap
                    if not include_source_comments:
                        break
            if best is None:
                best = placeholders.get((start, end))
                if best is None:
                    cue_id = f"slot-{len(placeholders) + 1}"
                    while cue_id in ids:
                        cue_id += "-"
                    fields = {"style": style, "layer": "0", "marginl": "0", "marginr": "0", "marginv": "0"}
                    best = placeholders[start, end] = Cue(cue_id, start, end, "", fields)
                    ids.add(cue_id)
            if include_source_comments:
                edition.source_comments.setdefault(best.id, []).append(_source_reference(label, source.text))
    # The sorted view above is only a timing lookup. Preserve primary ASS read
    # order within overlap components, where it controls layering/collisions.
    combined = [*edition.cues, *placeholders.values()]
    edition.cues = [combined[index] for index in presentation_order(combined, "ass")]
    edition.comments = sum(map(len, edition.source_comments.values()))
    edition.chronological = False
    return edition, {"primary_cues": len(primary), "placeholder_slots": len(placeholders),
                     "watermarks_removed": watermark_count, "style": style}
